/**
 * Generates the native SwiftUI app's compile-time configuration from
 * `config/mobile-runtime.json` — the same file the Capacitor build reads via
 * write-runtime-config.mjs.
 *
 * Having one source means the SwiftUI app and the Capacitor app can never
 * point at different backends, and changing the API base is a one-line edit in
 * a JSON file rather than a hunt through Swift.
 *
 * The output is committed so a fresh clone builds in Xcode without having to
 * run node first; re-run `npm run ios:native-config` after editing the JSON.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const cfgPath = resolve(root, 'config/mobile-runtime.json');
const outPath = resolve(root, 'ios/WebyarNative/Sources/Core/Networking/GeneratedConfig.swift');

const cfg = JSON.parse(readFileSync(cfgPath, 'utf8'));

const apiBaseUrl = (process.env.MOBILE_API_BASE_URL || process.env.IOS_API_BASE_URL || cfg.apiBaseUrl || '').trim();

// A native bundle is signed and shipped; a wrong or empty base URL would only
// surface as every request failing on a user's device. Fail the build instead.
if (!/^https:\/\/[^/]+$/i.test(apiBaseUrl)) {
  throw new Error(
    `[ios-native] Refusing to generate config with an invalid API base: "${apiBaseUrl}".\n` +
      '        Set it in config/mobile-runtime.json or MOBILE_API_BASE_URL=https://api.example.com',
  );
}

const supportUrl = (cfg.supportUrl || '').trim();
const defaultLocale = (cfg.defaultLocale || 'en').trim();
const locale = ['en', 'fa', 'tr'].includes(defaultLocale) ? defaultLocale : 'en';

const swift = `// GENERATED by scripts/ios/write-native-config.mjs — do not edit by hand.
// Source of truth: config/mobile-runtime.json (or MOBILE_API_BASE_URL).

import Foundation

enum GeneratedConfig {
    /// Origin the app sends every API request to.
    static let apiBaseURL = URL(string: ${JSON.stringify(apiBaseUrl)})!

    /// Opened from Settings → About.
    static let supportURL = ${supportUrl ? `URL(string: ${JSON.stringify(supportUrl)})` : 'URL?.none'}

    /// Language a first launch starts in, before the operator picks one.
    static let defaultLanguage = Language.${locale}
}
`;

writeFileSync(outPath, swift, 'utf8');
console.log(`[ios-native] ${apiBaseUrl} → ${outPath.replace(root + '/', '')}`);
