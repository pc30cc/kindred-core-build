/**
 * Generates the native SwiftUI app's compile-time configuration.
 *
 * WHERE THE ORIGIN COMES FROM, in order:
 *
 *   1. `MOBILE_API_BASE_URL` / `IOS_API_BASE_URL` — an explicit override, for
 *      building against a staging backend.
 *   2. **The platform itself.** `config/mobile-runtime.json` names a host to
 *      ask, and `GET /api/platform/origins` there answers with whatever
 *      `platform_domains.api_base_url` currently says (Super Admin →
 *      Branding). When the answer differs, it wins and is written back into
 *      the JSON, so the file becomes a cache of the last known answer rather
 *      than a second source of truth.
 *   3. The JSON as it stands — for an offline build, or a machine that cannot
 *      reach the platform.
 *
 * This matters because the rest of the system already works this way: see
 * `server/services/platformOrigins.ts`, whose rule is that domains must not be
 * baked into build artifacts. A signed app still needs one origin compiled in
 * to make its first request — it cannot ask the API where the API is — but
 * that value is a bootstrap, and the app replaces it with the platform's
 * answer on its first launch.
 *
 * The output is committed so a fresh clone builds in Xcode without having to
 * run node first; re-run `npm run ios:native-config` to pick up a move.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const cfgPath = resolve(root, 'config/mobile-runtime.json');
const outPath = resolve(root, 'ios/WebyarNative/Sources/Core/Networking/GeneratedConfig.swift');

const cfg = JSON.parse(readFileSync(cfgPath, 'utf8'));

const override = (process.env.MOBILE_API_BASE_URL || process.env.IOS_API_BASE_URL || '').trim();
let apiBaseUrl = (override || cfg.apiBaseUrl || '').trim();
let supportUrl = (cfg.supportUrl || '').trim();

/** Origin only, https only — a base URL with a path breaks every request. */
function asOrigin(raw) {
  if (typeof raw !== 'string' || !raw.trim()) return null;
  try {
    const url = new URL(raw.trim());
    return url.protocol === 'https:' ? url.origin : null;
  } catch {
    return null;
  }
}

/**
 * Asks the platform where it lives. Never fatal: a build with no network, or
 * against a host that has not deployed this route yet, falls back to the file.
 */
async function askPlatform(origin) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 8000);
  try {
    const res = await fetch(`${origin}/api/platform/origins`, { signal: controller.signal });
    if (!res.ok) return null;
    return await res.json();
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

if (!override && asOrigin(apiBaseUrl)) {
  const answer = await askPlatform(asOrigin(apiBaseUrl));
  const resolved = asOrigin(answer?.apiBaseUrl);
  if (resolved && resolved !== apiBaseUrl) {
    console.log(`[ios-native] platform_domains says ${resolved} (was ${apiBaseUrl}) — following it`);
    apiBaseUrl = resolved;
    cfg.apiBaseUrl = resolved;
    writeFileSync(cfgPath, `${JSON.stringify(cfg, null, 2)}\n`, 'utf8');
  } else if (!answer) {
    console.log(`[ios-native] could not reach ${apiBaseUrl} — using config/mobile-runtime.json as it stands`);
  }
  const help = asOrigin(answer?.helpCenterUrl) || asOrigin(answer?.publicBaseUrl);
  if (help && !supportUrl) supportUrl = `${help}/contact`;
}

// A native bundle is signed and shipped; a wrong or empty base URL would only
// surface as every request failing on a user's device. Fail the build instead.
if (!/^https:\/\/[^/]+$/i.test(apiBaseUrl)) {
  throw new Error(
    `[ios-native] Refusing to generate config with an invalid API base: "${apiBaseUrl}".\n` +
      '        Set it in config/mobile-runtime.json or MOBILE_API_BASE_URL=https://api.example.com',
  );
}

const defaultLocale = (cfg.defaultLocale || 'en').trim();
const locale = ['en', 'fa', 'tr'].includes(defaultLocale) ? defaultLocale : 'en';

const swift = `// GENERATED by scripts/ios/write-native-config.mjs — do not edit by hand.
//
// Source of truth: platform_domains.api_base_url (Super Admin → Branding),
// resolved at generation time. This is only the BOOTSTRAP the app uses for its
// very first request; see PlatformOrigin.swift, which replaces it with the
// platform's own answer and remembers that instead.

import Foundation

enum GeneratedConfig {
    /// Origin the app sends every API request to.
    static let apiBaseURL = URL(string: ${JSON.stringify(apiBaseUrl)})!

    /// Opened from Settings → About.
    static let supportURL = ${supportUrl ? `URL(string: ${JSON.stringify(supportUrl)})` : 'URL?.none'}

    /// Language a first launch starts in, before the operator picks one.
    static let defaultLanguage = Language.${locale}
}
`;

writeFileSync(outPath, swift, 'utf8');
console.log(`[ios-native] ${apiBaseUrl} → ${outPath.replace(root + '/', '')}`);
