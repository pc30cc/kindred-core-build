/**
 * Phase 6-S5-R7.5 §4 — per-file / per-rule lint baseline core.
 *
 * Pure functions only: no filesystem, no ESLint invocation. The CI runner
 * (`scripts/lint-baseline.mjs`) and the self-tests
 * (`src/test/lint/lintGate.test.ts`) share this module, so the gate that runs
 * in CI is exactly the gate that is tested.
 */

/** Normalizes an absolute ESLint file path to a repo-root-relative POSIX path. */
export function relPath(filePath, cwd) {
  const root = cwd.endsWith('/') ? cwd : `${cwd}/`;
  const p = filePath.startsWith(root) ? filePath.slice(root.length) : filePath;
  return p.split('\\').join('/');
}

/**
 * Builds the baseline snapshot from raw ESLint JSON results.
 * Files with zero problems ARE recorded (as `{}`) so that a clean file
 * becoming dirty is detectable.
 */
export function summarize(results, cwd = process.cwd()) {
  const rules = {};
  const files = {};
  let errors = 0;
  let warnings = 0;

  for (const file of results) {
    const name = relPath(file.filePath, cwd);
    const bucket = (files[name] ??= {});
    for (const m of file.messages ?? []) {
      const rule = m.ruleId ?? '(parse-error)';
      rules[rule] = (rules[rule] ?? 0) + 1;
      bucket[rule] = (bucket[rule] ?? 0) + 1;
      if (m.severity === 2) errors += 1;
      else warnings += 1;
    }
  }

  const sortObj = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));

  return {
    $comment:
      'Non-regression lint baseline (per-file and per-rule). Generated by scripts/lint-baseline.mjs. ' +
      'Numbers may only go DOWN; run `npm run lint:baseline:update` LOCALLY after fixing lint. CI must never update it.',
    totals: { errors, warnings, problems: errors + warnings },
    rules: sortObj(rules),
    files: Object.fromEntries(
      Object.entries(files)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([f, counts]) => [f, sortObj(counts)]),
    ),
  };
}

const totalOf = (counts) => Object.values(counts ?? {}).reduce((a, b) => a + b, 0);

/**
 * Compares a current snapshot against the recorded baseline.
 * Returns a list of human-readable regressions; empty means the gate passes.
 *
 * A reduction in one file never offsets an increase in another: every check is
 * one-directional and evaluated independently.
 */
export function compareBaseline(base, current) {
  const regressions = [];

  // Totals — an error may not be converted into extra warnings either.
  for (const key of ['errors', 'warnings', 'problems']) {
    const before = base.totals?.[key] ?? 0;
    const after = current.totals?.[key] ?? 0;
    if (after > before) regressions.push(`total ${key}: ${before} → ${after}`);
  }

  // Global per-rule counts.
  for (const [rule, count] of Object.entries(current.rules ?? {})) {
    const before = base.rules?.[rule] ?? 0;
    if (count > before) regressions.push(`rule ${rule}: ${before} → ${count}`);
  }

  // Per-file, per-rule counts. This is what blocks relocating a problem from
  // one file to another while the global count stays flat.
  const baseFiles = base.files ?? {};
  for (const [file, counts] of Object.entries(current.files ?? {})) {
    const known = Object.prototype.hasOwnProperty.call(baseFiles, file);
    const beforeCounts = baseFiles[file] ?? {};

    if (!known && totalOf(counts) > 0) {
      regressions.push(`new file with lint problems: ${file} (${totalOf(counts)})`);
      continue;
    }
    if (known && totalOf(beforeCounts) === 0 && totalOf(counts) > 0) {
      regressions.push(`previously clean file is now dirty: ${file} (${totalOf(counts)})`);
      continue;
    }
    for (const [rule, count] of Object.entries(counts)) {
      const before = beforeCounts[rule] ?? 0;
      if (count > before) {
        regressions.push(
          before === 0 ? `new rule in ${file}: ${rule} (${count})` : `${file} · ${rule}: ${before} → ${count}`,
        );
      }
    }
  }

  return regressions;
}

/** Total problems removed since the baseline (negative means regression). */
export function improvement(base, current) {
  return (base.totals?.problems ?? 0) - (current.totals?.problems ?? 0);
}