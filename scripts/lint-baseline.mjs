#!/usr/bin/env node
/**
 * Phase 6-S5-R7.4 §13 — machine-readable lint baseline + non-regression gate.
 *
 * The repository currently has thousands of pre-existing ESLint problems, so a
 * bare `eslint .` in CI is red on every commit and therefore enforces nothing.
 * This gate records the CURRENT counts in `.lint-baseline.json` and fails only
 * when a commit makes things WORSE — per rule and in total. Improvements are
 * always accepted, and `--update` re-records the (lower) numbers.
 *
 *   node scripts/lint-baseline.mjs           # enforce (CI)
 *   node scripts/lint-baseline.mjs --update  # re-record after fixing lint
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const BASELINE = '.lint-baseline.json';
const update = process.argv.includes('--update');

let raw = '';
try {
  raw = execFileSync('npx', ['eslint', '.', '-f', 'json'], {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  });
} catch (err) {
  // ESLint exits non-zero when problems exist — that is the normal path here.
  raw = err.stdout?.toString() ?? '';
  if (!raw.trim()) {
    console.error('[lint-baseline] eslint produced no JSON output:', err.stderr?.toString() ?? err.message);
    process.exit(2);
  }
}

const results = JSON.parse(raw);
const byRule = {};
let errors = 0;
let warnings = 0;
for (const file of results) {
  for (const m of file.messages) {
    const rule = m.ruleId ?? '(parse-error)';
    byRule[rule] = (byRule[rule] ?? 0) + 1;
    if (m.severity === 2) errors += 1;
    else warnings += 1;
  }
}
const current = {
  $comment:
    'Non-regression lint baseline. Generated by scripts/lint-baseline.mjs. Numbers may only go DOWN; run `npm run lint:baseline:update` after fixing lint.',
  totals: { errors, warnings, problems: errors + warnings },
  rules: Object.fromEntries(Object.entries(byRule).sort(([a], [b]) => a.localeCompare(b))),
};

if (update || !existsSync(BASELINE)) {
  writeFileSync(BASELINE, `${JSON.stringify(current, null, 2)}\n`);
  console.log(`[lint-baseline] recorded ${current.totals.problems} problems (${errors} errors, ${warnings} warnings).`);
  process.exit(0);
}

const base = JSON.parse(readFileSync(BASELINE, 'utf8'));
const regressions = [];
if (current.totals.errors > base.totals.errors) {
  regressions.push(`total errors ${base.totals.errors} → ${current.totals.errors}`);
}
if (current.totals.problems > base.totals.problems) {
  regressions.push(`total problems ${base.totals.problems} → ${current.totals.problems}`);
}
for (const [rule, count] of Object.entries(current.rules)) {
  const before = base.rules[rule] ?? 0;
  if (count > before) regressions.push(`${rule}: ${before} → ${count}`);
}

if (regressions.length) {
  console.error('[lint-baseline] LINT REGRESSION — new problems introduced:');
  for (const r of regressions) console.error(`  • ${r}`);
  console.error('\nFix the new findings. Do not run --update to silence them.');
  process.exit(1);
}

const improved = base.totals.problems - current.totals.problems;
console.log(
  `[lint-baseline] OK — ${current.totals.problems} problems (baseline ${base.totals.problems}` +
    `${improved > 0 ? `, ${improved} fewer 🎉 run npm run lint:baseline:update to lock it in` : ''}).`,
);
