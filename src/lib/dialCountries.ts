export const DIAL_COUNTRIES: readonly DialCountry[] = ROWS.map(([code, dial, trunk, minLength, maxLength, example]) => ({
  code,
  dial,
  trunkZero: trunk === 1,
  minLength,
  maxLength,
  example,
}));

const BY_CODE = new Map(DIAL_COUNTRIES.map((c) => [c.code, c]));

export function dialCountry(code: string | null | undefined): DialCountry | undefined {
  return code ? BY_CODE.get(code.toUpperCase()) : undefined;
}

/**
 * Where calling codes are shared (+1, +7, +44, …), the country that owns the
 * code's main numbering plan wins when a number is pasted without a country.
 */
export const MAIN_FOR_DIAL: Readonly<Record<string, string>> = {
  '1': 'US', '7': 'RU', '44': 'GB', '39': 'IT', '47': 'NO', '61': 'AU', '212': 'MA',
  '262': 'RE', '290': 'SH', '358': 'FI', '590': 'GP', '599': 'CW',
};

/** The country of an international number (`+905301234583` → TR), by the longest matching calling code. */
export function countryOfInternationalNumber(e164: string, preferred?: string | null): DialCountry | undefined {
  const digits = e164.replace(/\D/g, '');
  for (let len = 3; len >= 1; len -= 1) {
    const dial = digits.slice(0, len);
    const matches = DIAL_COUNTRIES.filter((c) => c.dial === dial);
    if (matches.length === 0) continue;
    return (
      matches.find((c) => c.code === preferred)
      ?? matches.find((c) => c.code === MAIN_FOR_DIAL[dial])
      ?? matches[0]
    );
  }
  return undefined;
}

/** Digits the user typed for the national part: Persian/Arabic digits made Latin, everything else dropped. */
export function nationalDigits(input: string): string {
  return input
    .replace(/[\u06F0-\u06F9]/g, (d) => String(d.charCodeAt(0) - 0x06f0))
    .replace(/[\u0660-\u0669]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/\D/g, '');
}

/** The E.164 number for a country and what was typed after it (`TR`, `0530 123 45 83` → `+905301234583`). */
export function toE164(country: DialCountry, nationalInput: string): string {
  const all = nationalDigits(nationalInput);
  const digits = country.trunkZero ? all.replace(/^0+/, '') : all;
  return digits ? `+${country.dial}${digits}` : '';
}

/** How many digits the national part has, without the trunk 0. */
export function nationalLength(country: DialCountry, nationalInput: string): number {
  const digits = nationalDigits(nationalInput);
  return (country.trunkZero ? digits.replace(/^0+/, '') : digits).length;
}

/** Whether the national part has a possible length for the country. */
export function isPossibleNational(country: DialCountry, nationalInput: string): boolean {
  const length = nationalLength(country, nationalInput);
  return length >= country.minLength && length <= country.maxLength && country.dial.length + length <= 15;
}

/** Path of a country's flag image. */
export function flagUrl(code: string): string {
  return `/flags/${code.toUpperCase()}.svg`;
}
