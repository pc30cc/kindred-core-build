/**
 * Every country's international calling code, for the phone number field's
 * country picker (src/components/phone/PhoneNumberField.tsx).
 *
 * Generated once from libphonenumber-js 1.13.15 (MIT) metadata:
 *   [ISO 3166-1 alpha-2, calling code, trunk "0" (dialled at home before the
 *    national number, dropped after the country code), shortest and longest
 *    national number, an example mobile number in national format].
 * Country names are not stored: they come from the browser's own
 * `Intl.DisplayNames`, in the interface language (fa / en / tr).
 * Flags: public/flags/<ISO>.svg (country-flag-icons 1.6.20, MIT).
 */

export interface DialCountry {
  /** ISO 3166-1 alpha-2, e.g. 'TR'. */
  code: string;
  /** Calling code without '+', e.g. '90'. */
  dial: string;
  /** Whether a leading 0 typed at home is the trunk prefix (dropped in E.164). */
  trunkZero: boolean;
  minLength: number;
  maxLength: number;
  /** An example mobile number in national format, e.g. '501 234 56 78'. */
  example: string;
}

